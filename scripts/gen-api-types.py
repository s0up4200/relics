#!/usr/bin/env python3
"""Generate src/api/wire.rs from the Silo server openapi.json.

Usage: scripts/gen-api-types.py [SILO_SERVER_CHECKOUT]   (default: $SILO_SERVER or ~/github/oss/silo-server)

The script keeps only the schemas that the operations in api/operations.txt reach.
It removes `additionalProperties: false` and every `enum`, so that an unknown field
or enum value from a newer server still decodes. Then it runs typify 0.8.0
(`cargo install cargo-typify@0.8.0 --locked`). Run it by hand and commit the result.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SERVER = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SILO_SERVER", "~/github/oss/silo-server")).expanduser()
OUT = REPO / "src/api/wire.rs"
PREFIX = "#/components/schemas/"
DROP_KEYS = {"enum", "examples", "patternDescription"}


def refs(node):
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith(PREFIX):
            yield ref[len(PREFIX):]
        for value in node.values():
            yield from refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from refs(value)


def lenient(node):
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key in DROP_KEYS or (key == "additionalProperties" and value is False):
                continue
            if key == "$ref" and isinstance(value, str) and value.startswith(PREFIX):
                value = "#/$defs/" + value[len(PREFIX):]
            if key == "properties":
                # The keys of `properties` are field names, not schema keywords.
                out[key] = {name: lenient(prop) for name, prop in value.items()}
            else:
                out[key] = lenient(value)
        return out
    if isinstance(node, list):
        return [lenient(value) for value in node]
    return node


def main():
    spec = json.loads((SERVER / "contracts/api/v2/openapi.json").read_text())
    commit = subprocess.check_output(["git", "-C", str(SERVER), "rev-parse", "HEAD"], text=True).strip()
    wanted = {line.strip() for line in (REPO / "api/operations.txt").read_text().splitlines()
              if line.strip() and not line.startswith("#")}

    found, roots = set(), set()
    for path in spec["paths"].values():
        for op in path.values():
            if isinstance(op, dict) and op.get("operationId") in wanted:
                found.add(op["operationId"])
                roots.update(refs(op))
    if wanted - found:
        sys.exit(f"operations not in openapi.json: {sorted(wanted - found)}")

    schemas = spec["components"]["schemas"]
    keep, stack = set(), list(roots)
    while stack:
        name = stack.pop()
        if name not in keep:
            keep.add(name)
            stack.extend(refs(schemas[name]))

    defs = {name: lenient(schemas[name]) for name in sorted(keep)}
    with tempfile.TemporaryDirectory() as tmp:
        schema = Path(tmp) / "silo-v2.json"
        schema.write_text(json.dumps({"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs}))
        out = Path(tmp) / "wire.rs"
        # typify formats with rustfmt. Without rustup it finds rustfmt only through $RUSTFMT.
        env = {"RUSTFMT": shutil.which("rustfmt") or "rustfmt", **os.environ}
        subprocess.run(["cargo", "typify", "--no-builder", str(schema), "--output", str(out)], check=True, env=env)
        body = out.read_text()

    header = (
        "//! Wire types of the Silo API v2. Generated by scripts/gen-api-types.py with typify 0.8.0.\n"
        f"//! Server commit: {commit}. Do not edit by hand.\n"
        "#![allow(clippy::all, clippy::pedantic, dead_code, unused_imports)]\n\n"
    )
    OUT.write_text(header + body)
    print(f"{len(found)} operations, {len(keep)} schemas -> {OUT.relative_to(REPO)}")


main()
